"""The Acid Eva-01 theme's fonts (firmware/gen/eva_font.h), in the felucca_font_t format of gen_font.py:
  D  values and page titles     InterDisplay Black 16 px, tabular figures
  M  words, long values         InterDisplay Black 12 px, 12 % narrower
  A  knob labels                Inter Bold 10 px, open tracking
Capitals, digits and signs only (32..95): lower case folds to capitals in glyph(), units stay in Terminus.
Anti-aliased, 4-bit alpha; cv_text blends the edges over what is under them (text on colour blocks).
Inter: SIL OFL 1.1 (assets/fonts/Inter-LICENSE.txt).

  tools/gen_eva_font.py [out.h] [--png sheet.png]
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONTS = Path(__file__).resolve().parents[1] / "assets" / "fonts"
PAD = 2
FIRST, LAST = 32, 95
# name, file, px, x stretch, tracking (px), tabular digits
SIZES = [("D", "InterDisplay-Black.otf", 16, 1.0, 0.0, True),
         ("M", "InterDisplay-Black.otf", 12, 0.88, 0.0, True),
         ("A", "Inter-Bold.otf", 10, 1.0, 0.7, False)]


def render(file, px, stretch, track, tab):
    font = ImageFont.truetype(str(FONTS / file), px)
    asc, desc = font.getmetrics()
    S = 4                                           # stretch at 4x, then down: clean edges
    big = ImageFont.truetype(str(FONTS / file), px * S)
    dadv = max(big.getlength(str(d)) for d in range(10))
    cells = []
    for c in range(FIRST, LAST + 1):
        ch = chr(c)
        a = big.getlength(ch)
        adv_big = dadv if (tab and ch.isdigit()) else a
        off = (adv_big - a) / 2
        W = int(adv_big * stretch) + 4 * PAD * S + S
        img = Image.new("L", (W, (asc + desc) * S), 0)
        d = ImageDraw.Draw(img)
        # draw stretched: render plain, then scale x
        tmp = Image.new("L", (int(adv_big) + 4 * PAD * S, (asc + desc) * S), 0)
        ImageDraw.Draw(tmp).text((PAD * S + off, 0), ch, font=big, fill=255)
        tmp = tmp.resize((max(1, int(tmp.width * stretch)), tmp.height), Image.LANCZOS)
        img.paste(tmp, (0, 0))
        small = img.resize((W // S, asc + desc), Image.LANCZOS)
        adv = int(round(adv_big * stretch / S + track))
        cells.append((ch, adv, small))
    # vertical crop: from the top of the capitals to the lowest ink of any glyph
    top, bot = 99, 0
    for ch, adv, im in cells:
        bb = im.getbbox()
        if bb and ch not in "_,":
            top = min(top, bb[1]); bot = max(bot, bb[3])
    bb = cells[ord("_") - FIRST][2].getbbox()
    bot = max(bot, bb[3] if bb else bot)
    h = bot - top
    glyphs = []
    for ch, adv, im in cells:
        bb = im.getbbox()
        bw = max(adv + 2 * PAD, (bb[2] if bb else 0))
        bw += bw & 1
        im = im.crop((0, top, bw, top + h))
        px_ = [min(15, (v + 8) // 17) for v in im.tobytes()]
        glyphs.append((adv, bw, px_))
    return h, glyphs


def main(out, png=None):
    lines = ["/* generated by tools/gen_eva_font.py from InterDisplay-Black.otf / Inter-Bold.otf (SIL OFL 1.1) */",
             "#pragma once", "#include <stdint.h>", ""]
    sheet = []
    for name, file, px, st, tr, tab in SIZES:
        h, glyphs = render(file, px, st, tr, tab)
        data, offs = [], []
        for adv, bw, g in glyphs:
            offs.append(len(data))
            for y in range(h):
                row = g[y * bw:(y + 1) * bw]
                for x in range(0, bw, 2):
                    data.append((row[x] << 4) | row[x + 1])
        assert len(data) < 65536
        lines.append(f"static const uint8_t FONT_{name}_DATA[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const uint16_t FONT_{name}_OFF[{len(offs)}] = {{" + ", ".join(map(str, offs)) + "};")
        lines.append(f"static const uint8_t FONT_{name}_ADV[{len(glyphs)}] = {{" + ", ".join(str(a) for a, _, _ in glyphs) + "};")
        lines.append(f"static const uint8_t FONT_{name}_BW[{len(glyphs)}] = {{" + ", ".join(str(b) for _, b, _ in glyphs) + "};")
        lines.append(f"static const felucca_font_t FONT_{name} = {{ {h}, {PAD}, {FIRST}, {LAST}, "
                     f"FONT_{name}_ADV, FONT_{name}_BW, FONT_{name}_OFF, FONT_{name}_DATA }};")
        lines.append("")
        ga = glyphs[ord("A") - FIRST]
        rows = [y for y in range(h) if any(ga[2][y * ga[1]:(y + 1) * ga[1]])]
        lines.append(f"#define FONT_{name}_CAP {rows[0]}   /* the first row of a capital */")
        lines.append(f"#define FONT_{name}_BASE {rows[-1] + 1}   /* the row under a capital (the baseline) */")
        lines.append("")
        print(f"cap {rows[0]}..{rows[-1]+1}")
        print(f"font {name}: {file} {px}px h {h}, digit adv {glyphs[ord('0') - FIRST][0]}, {len(data)} B")
        sheet.append((name, h, glyphs))
    Path(out).write_text("\n".join(lines))
    if png:
        W = 480
        im = Image.new("L", (W, sum(h + 8 for _, h, _ in sheet) * 2), 0)
        y = 0
        for name, h, glyphs in sheet:
            x = 0
            for adv, bw, g in glyphs:
                if x + bw > W:
                    break
                for yy in range(h):
                    for xx in range(bw):
                        v = g[yy * bw + xx]
                        if v:
                            im.putpixel((x + xx - PAD, y + yy), v * 17)
                x += adv
            y += h + 8
        im.crop((0, 0, W, y)).resize((W * 2, y * 2), Image.NEAREST).save(png)


if __name__ == "__main__":
    a = sys.argv[1:]
    out = a[0] if a and not a[0].startswith("--") else str(Path(__file__).resolve().parents[1] / "firmware" / "gen" / "eva_font.h")
    main(out, a[a.index("--png") + 1] if "--png" in a else None)
