# ND-07 // MONOLITH (FM-1): the lookup tables the integer DSP uses (the chip has no FPU and no libgcc float).
# Writes firmware/src/nd07_tables.h. Run it again only if you change a curve:  python3 tools/gen_nd07_tables.py
import math, pathlib

FS = 44100.0
OUT = pathlib.Path(__file__).resolve().parent.parent / "firmware" / "src" / "nd07_tables.h"
L = []


def arr(ctype, name, vals, per=12):
    L.append(f"static const {ctype} {name}[{len(vals)}] = {{")
    for i in range(0, len(vals), per):
        L.append("    " + ", ".join(str(int(v)) for v in vals[i:i + per]) + ",")
    L.append("};")


def const(name, v, comment=""):
    L.append(f"#define {name} {int(v)}" + (f"   /* {comment} */" if comment else ""))


def q(v, bits, lo=None, hi=None):
    x = int(round(v * (1 << bits)))
    if lo is not None: x = max(lo, x)
    if hi is not None: x = min(hi, x)
    return x


# log-frequency index: f = 20 * 1000^(li / 1023), li 0..1023 (20 Hz .. 20 kHz)
NLI = 1024
def li_of(f): return max(0, min(NLI - 1, int(round(1023 * math.log(f / 20.0) / math.log(1000.0)))))
def f_of(li): return 20.0 * 1000.0 ** (li / 1023.0)
LI_PER_OCT = 1023 / math.log2(1000.0)

L.append("/* generated by tools/gen_nd07_tables.py: do not edit */")
L.append("#pragma once")
arr("int16_t", "T_SIN", [q(math.sin(2 * math.pi * i / 1024), 15, -32767, 32767) for i in range(1025)])
arr("uint16_t", "T_HCOS", [q(0.5 * (1 - math.cos(math.pi * i / 256)), 15, 0, 32767) for i in range(257)])       # 0 -> 1 rising half cosine
arr("uint16_t", "T_HANN", [q(0.5 * (1 - math.cos(2 * math.pi * i / 256)), 15, 0, 32767) for i in range(257)])  # full Hann over 256
arr("uint16_t", "T_SQSIN", [q(math.sqrt(max(0.0, math.sin(math.pi * i / 256))), 15, 0, 32767) for i in range(257)])


def ftanh(x):
    x = max(-3.0, min(3.0, x)); x2 = x * x
    return x * (27 + x2) / (27 + 9 * x2)


arr("uint16_t", "T_TANH", [q(ftanh(i / 256.0), 15, 0, 32767) for i in range(1025)])           # x 0..4 step 1/256
arr("uint16_t", "T_SOFTK", [q((i / 256.0) if i / 256.0 <= 0.75 else ftanh(i / 256.0), 15, 0, 32767) for i in range(1025)])
arr("uint32_t", "T_EXP2", [q(2 ** (i / 256.0), 16) for i in range(257)])                     # 2^(i/256), Q16
arr("uint16_t", "T_LOG2F", [q(math.log2(1 + i / 256.0), 8) for i in range(257)])              # log2(1+i/256), Q8
arr("uint32_t", "T_G", [q(math.tan(math.pi * min(f_of(li), 0.44 * FS) / FS), 16) for li in range(NLI)])   # ZDF g, Q16
arr("uint16_t", "T_CUT", [q(1 - math.exp(-2 * math.pi * min(f_of(li), 0.46 * FS) / FS), 16, 1, 65535) for li in range(NLI)])
arr("uint16_t", "T_HZ", [round(f_of(li)) for li in range(NLI)])
const("LI_55", li_of(55.0)); const("LI_MAX", li_of(0.44 * FS)); const("LI_PER_OCT_Q8", round(LI_PER_OCT * 256))
const("LI_DEPTH_K", round(3.2 * LI_PER_OCT / (100 * 32768) * (1 << 20)), "depth(-100..100)*mod(Q15)*this >> 20 = li offset (3.2 oct)")


def logtab(lo, hi, n): return [lo * (hi / lo) ** (i / (n - 1)) for i in range(n)]


arr("uint16_t", "T_ATT_MS", [round(v) for v in logtab(1, 3000, 64)])
arr("uint16_t", "T_DEC_MS", [round(v) for v in logtab(10, 5000, 64)])
arr("uint16_t", "T_REL_MS", [round(v) for v in logtab(5, 8000, 64)])
arr("uint16_t", "T_GLIDE_MS", [0] + [round(v) for v in logtab(5, 2000, 63)])
arr("uint16_t", "T_DTIME_MS", [round(v) for v in logtab(10, 1000, 64)])
arr("uint16_t", "T_FRATE_CHZ", [round(v * 100) for v in logtab(0.05, 10.0, 64)])
arr("uint16_t", "T_LRATE_CHZ", [round(v * 100) for v in logtab(0.05, 30.0, 64)])
arr("uint16_t", "T_RDEC_MS", [round(v) for v in logtab(200, 20000, 64)])


def ulaw_dec(u):
    u = ~u & 0xFF
    sign, exp, mant = u & 0x80, (u >> 4) & 7, u & 15
    v = ((mant << 3) + 0x84) << exp
    v -= 0x84
    return -v if sign else v


arr("int16_t", "T_ULAW", [ulaw_dec(u) for u in range(256)])
arr("uint16_t", "T_FLT_LI", [li_of(v) for v in logtab(250, 15000, 64)])
arr("uint16_t", "T_RF_LI", [li_of(v) for v in logtab(80, 14000, 64)])
arr("uint16_t", "T_RATE_CHZ", [round(v * 100) for v in logtab(0.2, 18.0, 64)])
arr("uint16_t", "T_XLO_LI", [li_of(v) for v in logtab(60, 400, 32)])
arr("uint16_t", "T_XHI_LI", [li_of(v) for v in logtab(1200, 6000, 32)])
arr("uint32_t", "T_SEMI", [q(2 ** (s / 12.0), 16) for s in range(-48, 49)])                  # semitone -48..48 -> ratio Q16
arr("uint32_t", "T_DB2LIN", [q(10 ** ((-72 + i * 0.25) / 20), 12) for i in range(481)])      # -72..+48 dB, 0.25 steps, Q12
# env follower alpha: t = 0.5 ms * 2^(i/16), alpha = 1 - exp(-1/(t*fs)), Q16
arr("uint16_t", "T_ALPHA", [q(1 - math.exp(-1 / (0.0005 * 2 ** (i / 16.0) * FS)), 16, 1, 65535) for i in range(256)])
# OTT crossovers: 32 steps each, the original split (88.3 Hz, 2.5 kHz) exactly on step 10 / 12
def anchored(lo, mid, hi, n, at): return [lo * (mid / lo) ** (i / at) if i <= at else mid * (hi / mid) ** ((i - at) / (n - 1 - at)) for i in range(n)]
arr("uint16_t", "T_OXLO_LI", [li_of(v) for v in anchored(40, 88.3, 400, 32, 10)])
arr("uint16_t", "T_OXHI_LI", [li_of(v) for v in anchored(800, 2500, 8000, 32, 12)])
const("SQRT2_Q16", round(math.sqrt(2) * 65536))
# per-sample decay factors for the pad sources, Q30: exp(-rate/fs)
for r in (6.5, 6.0, 5.5, 4.2, 10.0, 8.0):
    const(f"DK_{str(r).replace('.', '_')}", q(math.exp(-r / FS), 30))
const("PH_PER_HZ", round(2 ** 32 / FS), "phase step per Hz (2^32 / fs)")
const("C4_INC", round(261.6256 * 2 ** 32 / FS), "C4 phase step")
const("LIM_REL_Q16", q(math.exp(-1 / (0.045 * FS)), 16))
const("DC_C_Q15", q(math.exp(-2 * math.pi * 18 / FS), 15))
const("LIM_CEIL", q(0.9772, 15))
const("RF_ATT_Q16", q(1 - math.exp(-1 / (0.005 * FS)), 16))
const("RF_REL_Q16", q(1 - math.exp(-1 / (0.075 * FS)), 16))
const("LFO_PH_PER_CHZ", round(2 ** 32 / FS / 100), "LFO phase step per 0.01 Hz")
OUT.write_text("\n".join(L) + "\n")
print("wrote", OUT, sum(len(x) for x in L), "chars")
